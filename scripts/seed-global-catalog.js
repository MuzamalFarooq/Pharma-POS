export async function seedGlobalCatalog() {
  console.log('Seeding Global Medicine Catalog...');
  let createdCount = 0;
  let updatedCount = 0;

  for (const item of standardGlobalMedicines) {
    const existing = await prisma.globalMedicine.findFirst({
      where: {
        OR: [
          ...(item.barcode ? [{ barcode: item.barcode }] : []),
          ...(item.sku ? [{ sku: item.sku }] : []),
          { name: item.name },
        ],
      },
    });

    if (existing) {
      await prisma.globalMedicine.update({
        where: { id: existing.id },
        data: item,
      });
      updatedCount++;
    } else {
      await prisma.globalMedicine.create({
        data: item,
      });
      createdCount++;
    }
  }

  console.log(`Global catalog seeded successfully: ${createdCount} created, ${updatedCount} updated.`);
}

if (process.argv[1]?.endsWith('seed-global-catalog.js')) {
  seedGlobalCatalog()
    .catch((e) => {
      console.error('Seed error:', e);
      process.exit(1);
    })
    .finally(() => prisma.$disconnect());
}
